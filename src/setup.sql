BEGIN;

CREATE TABLE IF NOT EXISTS public.organization (
    organization_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    contact_email VARCHAR(255) NOT NULL UNIQUE,
    logo_filename VARCHAR(255) NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS organization_name_key
    ON public.organization (name);

CREATE TABLE IF NOT EXISTS public.project (
    project_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    organization_id INTEGER NOT NULL
        REFERENCES public.organization (organization_id) ON DELETE CASCADE,
    name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.category (
    category_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.project_category (
    project_id INTEGER NOT NULL
        REFERENCES public.project (project_id) ON DELETE CASCADE,
    category_id INTEGER NOT NULL
        REFERENCES public.category (category_id) ON DELETE CASCADE,
    PRIMARY KEY (project_id, category_id)
);

